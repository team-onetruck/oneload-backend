"""Shortest path over registered passages, turned into step-by-step guidance.

No step text or arrow is generated by an LLM: instructions come from the map's edge templates and
the street-view arrow is pure geometry, so a route can only contain passages someone surveyed.
"""

from dataclasses import dataclass

import networkx as nx

from app.domain.mapdata import Edge, MapData, Text


@dataclass(frozen=True)
class RouteStep:
    step_id: str
    kind: str
    from_node_id: str
    to_node_id: str
    distance_m: float
    instruction: Text
    pano_id: str | None
    arrow_yaw_deg: float | None


@dataclass(frozen=True)
class PlannedRoute:
    path_node_ids: list[str]
    steps: list[RouteStep]

    @property
    def distance_m(self) -> float:
        return sum(s.distance_m for s in self.steps)


def plan_route(
    map_: MapData, start_node_id: str, goal_node_id: str, *, avoid_stairs: bool = False
) -> PlannedRoute | None:
    graph = nx.DiGraph()
    for edge in map_.edges:
        graph.add_edge(edge.from_, edge.to, edge=edge)

    def cost(_u: str, _v: str, data: dict) -> float | None:
        edge: Edge = data["edge"]
        return None if avoid_stairs and edge.type == "stairs" else edge.distance_m  # None hides the edge

    try:
        path = nx.dijkstra_path(graph, start_node_id, goal_node_id, weight=cost)
    except (nx.NetworkXNoPath, nx.NodeNotFound):
        return None

    edges = [graph.edges[u, v]["edge"] for u, v in zip(path, path[1:], strict=False)]
    return PlannedRoute(path_node_ids=path, steps=[_step(map_, i, e) for i, e in enumerate(edges, start=1)])


def _step(map_: MapData, index: int, edge: Edge) -> RouteStep:
    pano = map_.panorama_by_node.get(edge.from_)
    return RouteStep(
        step_id=f"s{index}",
        kind=_step_kind(map_, edge),
        from_node_id=edge.from_,
        to_node_id=edge.to,
        distance_m=edge.distance_m,
        instruction=edge.instruction,
        pano_id=pano.pano_id if pano else None,
        # Where the next leg points inside this photo: the photo's north plus the leg's map bearing.
        arrow_yaw_deg=_wrap_degrees(pano.north_yaw_deg + edge.heading_deg) if pano else None,
    )


def _step_kind(map_: MapData, edge: Edge) -> str:
    if edge.type == "corridor":
        return "walk"
    if edge.type in ("gate", "elevator"):
        return edge.type
    start = map_.node_by_id[edge.from_].position.y
    end = map_.node_by_id[edge.to].position.y
    return f"{edge.type}_{'down' if end < start else 'up'}"


def _wrap_degrees(angle: float) -> float:
    """Normalise to (-180, 180]."""
    wrapped = (angle + 180) % 360 - 180
    return 180.0 if wrapped == -180 else wrapped
